/**
 * **번들러 적재로 Kotlin 원문을 끌어오는 상설 양성 대조**(M12/gates-web-read-3 — ⓑ⑤).
 *
 * 이 모듈은 **일부러** vite 의 glob 적재로 web 밖 Kotlin 디렉터리를 `?raw` 로 끌어온다. 끌어오는
 * 주체가 소비자 코드가 아니라 **vite 메인 프로세스**라는 것이 이 축의 성질이다 — 소비자 프로세스의
 * `fs` 표면을 감싸는 층은 그 읽기를 보지 못했고, glob 패턴에 **확장자 토큰이 없으면** 정적 술어도
 * 보지 못했다(착수 실측: 42 모듈이 적재됐다).
 *
 * 그래서 층을 **vite 설정에서** 세운다. 이 모듈을 적재하려는 시도는 그때부터 실패하고, 그 실패를
 * `kotlin-read-guard.test.mjs` 가 **동적 import 의 거절**로 잰다. 정적으로 import 하면 이 파일을
 * 쥔 test 파일 자체가 적재되지 못하므로 — 그 꼴은 대조가 아니라 고장이다 — 쥐는 자리를 동적으로
 * 둔다.
 *
 * **표면에 뜨는 오류 문면은 층의 것이 아니다**(알려진 제한). vite 가 층의 거부를 잡고 상대 경로로
 * 다시 열어 `ENOENT` 를 내므로 원인을 말하지 않는다. 그 대신 **통제군**이 이 실패가 Kotlin 축에서만
 * 일어남을 든다(저장소 밖 비 Kotlin 파일의 같은 `?raw` glob 은 그대로 적재된다 — 실측 1 모듈).
 *
 * 패턴에 확장자 토큰을 적지 않는 것은 **이 대조의 전제**다. 적으면 정적 술어가 먼저 잡아 「런타임
 * 층이 없으면 열린다」를 재지 못한다.
 */
/**
 * **glob 은 최상위에서 돌고 값을 만져야 한다** — 두 번 죽은 대조를 고친 자리다. ① 함수 안에 두면
 * 적재만으로는 아무것도 열지 않는다 ② **키만** 세면 `?raw` 값이 **게으르게** 남아 역시 아무것도
 * 열지 않는다(실측: 키 42 개를 세고도 층은 아무것도 보지 못했다). 값의 길이를 더해 **내용을
 * 만진다** — 그때 비로소 읽기가 일어난다.
 */
export const kotlinRawLength = Object.values(
  import.meta.glob('../../procurement/src/main/kotlin/bidvector/procurement/*', {
    query: '?raw',
    import: 'default',
    eager: true,
  }),
).reduce((total, text) => total + String(text).length, 0);
