/**
 * 부재 어휘의 **한 자리**(M14/14A ④).
 *
 * 앞 판은 같은 글자가 상수 넷과 손으로 적은 JSX 다섯에 흩어져 있었다. 그 중복이 문제인 것이
 * 아니라, 흩어진 글자가 **서로 다른 사실**을 한 얼굴로 말하는 것이 문제였다 — 알림함 배지는
 * **응답이 오기 전**에도 그 글자를 냈고, 운영자가 그것을 「서버가 0 건이라고 답했다」로 읽을 수
 * 있었다.
 *
 * 그래서 부재는 **사유를 지닌 값**이다. 값은 사유만 들고 글자는 표가 낸다 — 값에 글자를 싣는
 * 칸이 없으므로 「사유는 붙였는데 글자는 옛것」이 타입에서 설 수 없다.
 *
 * **사유가 늘면 이 표가 한 자리에서 늘어난다.** 오늘 둘인 것은 오늘 일어나는 일이 둘이기
 * 때문이고, 셋째가 필요해지는 자리(「그 종류에는 해당 값이 없다」 같은)는 그것을 아는 호출부가
 * 사유를 **인자로** 받게 되는 날이다.
 */
export const ABSENCE_REASONS = ['notSent', 'notLoaded'] as const;

export type AbsenceReason = (typeof ABSENCE_REASONS)[number];

/**
 * 사유 → 문면. **전수**이고 `satisfies` 가 그 등식을 든다.
 *
 * 문면은 **옛 어휘를 부분 문자열로도 담지 않는다**. 담으면 이 slice 의 측정 acceptance(좁힌
 * 전수 훑기 0)가 영영 0 에 닿지 못한다 — 이 함정은 실제로 있다(생성 타입의 설명 한 줄이 같은
 * 부분 일치로 걸린다).
 *
 *  · `notSent` — **응답은 왔고 그 칸이 비었다.** 세상에 그 값이 없다는 뜻이 아니라, 우리가 받은
 *    답에 그것이 실려 있지 않다는 뜻이다. 화면이 아는 것은 거기까지다.
 *  · `notLoaded` — **아직 묻고 답을 기다린다.** 0 이 아니고 없음도 아니다.
 */
export const ABSENCE_TEXT = {
  notSent: '주어지지 않음',
  notLoaded: '아직 받지 못함',
} as const satisfies Record<AbsenceReason, string>;

/**
 * 사유 하나의 문면. **부재를 그리는 모든 자리가 이 함수를 지난다** — 글자를 손으로 적는 길이
 * 남아 있지 않으므로, 사유를 고르지 않고는 부재를 그릴 수 없다.
 *
 * 값을 감싸는 객체를 두지 않는다: 사유 유니온 자체가 그 타입이고, 자리마다 **필수 인자**로
 * 서는 것이 「사유를 지닌 값」의 실체다. 껍데기를 하나 더 두면 쓰지 않는 API 가 남는다.
 */
export function absenceTextOf(reason: AbsenceReason): string {
  return ABSENCE_TEXT[reason];
}
