-- M15/15C — 사업자등록번호 **선택** 입력(마일스톤 15 계약 slice 15C, 2026-11-21).
--
-- V22 는 이 열을 **일부러 만들지 않았다**(그 머리말의 「슬롯을 만들지 않는 것」 · scope P4).
-- 운영자 지시 2026-11-21 「사업자번호 필수 사항도 옵션으로 — 가입·사용 조건을 완화해서 테스트가
-- 쉽게」가 그 결정을 뒤집는다. 뒤집는 줄이므로 사유와 날짜를 여기 적는다: 지금 이 값은 **어디에도
-- 저장되지 않으므로** 「필수를 선택으로 낮추는 일」이 아니라 **선택 칸을 새로 두는 일**이다.
--
-- 번호는 마일스톤 15 계약이 배정했다(15A=V28 · 15B=V29 · 15C=V30) — 세 레인이 병렬이라 충돌을
-- 번호 배정으로 막는다. 머지 순서가 어긋나면 뒤 slice 가 번호를 옮긴다.
--
-- **저장되는 꼴은 숫자 10자리 하나**다. 화면의 `3-2-5` 는 보여 주는 서식이고, 하이픈 표기를
-- 열 자리로 접는 자리는 애플리케이션의 값 타입(`BusinessRegistrationNumber`) **하나**다 —
-- 두 꼴을 표에 함께 담으면 같은 사업자가 서로 다른 두 행이 된다.
--
-- **검증번호(체크섬)를 걸지 않는다** — M15 계약의 완화 지시다. 국세청 진위 확인도 범위 밖이라
-- 이 열의 값이 실제 사업자의 것인지는 표도 앱도 모른다. CHECK 는 자릿수만 본다.
--
-- 술어를 `[0-9]` 로 적는다(`\d` 가 아니라): 두 표기의 뜻이 PostgreSQL 의 정규식 방언과 로케일에
-- 따라 갈릴 자리를 남기지 않는다. 앱의 값 타입도 같은 문자 집합을 쓴다(전각 숫자는 양쪽이 거부).
--
-- NULL 이 「비워 둠」이다 — 빈 문자열을 「미설정」으로 쓰지 않는다(상호와 같은 규율). 그래서 빈
-- 문자열은 CHECK 가 거부하고, 지우기는 NULL 로 쓴다.
ALTER TABLE account_business_profile
    ADD COLUMN business_registration_number TEXT
        CHECK (business_registration_number IS NULL
            OR business_registration_number ~ '^[0-9]{10}$');

-- 앱 역할의 UPDATE 는 **열 단위**다(V22 의 관례 — 소유자 열을 바꾸는 길이 권한 층에 없다).
-- 새 열을 그 목록에 더하지 않으면 사업 정보 upsert 의 `DO UPDATE SET` 이 권한 거부로 떨어진다.
-- INSERT 는 V22 가 표 단위로 주었으므로 새로 줄 것이 없다.
GRANT UPDATE (business_registration_number) ON account_business_profile TO bidvector_app;
